'use strict';
const v = require('vscode');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const wait = ms => new Promise(r => setTimeout(r, ms));
exports.run = async () => {
  const extension = v.extensions.getExtension('satsuki-thyme.markdown-preview-via-js-transforms');
  const api = await extension.activate();
  const root = process.env.MPJST_TEST_ROOT;
  const input = path.join(root, 'input.md'), script = path.join(root, 'transforms', 'identity.cjs');
  const inputDocument = await v.workspace.openTextDocument(v.Uri.file(input));
  await v.window.showTextDocument(inputDocument);
  const first = await api.controller.runPair({ root, input, script });
  assert.equal(first.status, 'success');
  const resultDocument = await v.workspace.openTextDocument(first.uri);
  assert.equal(resultDocument.languageId, 'markdown');
  assert.equal(resultDocument.getText(), '# First 🌿');
  await wait(750);
  const previewTabs = () => v.window.tabGroups.all.flatMap(g => g.tabs).filter(tab => tab.input instanceof v.TabInputCustom && tab.input.viewType === 'vscode.markdown.preview.editor' && tab.input.uri.toString() === first.uri.toString());
  assert.equal(previewTabs().length, 1);
  const originalTab = previewTabs()[0];
  await fs.writeFile(input, '# Saved edit');
  await fs.writeFile(script, 'module.exports=({text})=>text+"\\n\\nChanged script"');
  await wait(750);
  await v.commands.executeCommand('markdownPreviewViaJsTransforms.reopenPreview');
  assert.equal(resultDocument.getText(), '# First 🌿');
  assert.equal((await v.commands.executeCommand('markdownPreviewViaJsTransforms.rerun')).status, 'success');
  for (let n = 0; n < 60 && !resultDocument.getText().includes('Changed script'); n++) await wait(50);
  assert.equal(resultDocument.getText(), '# Saved edit\n\nChanged script');
  assert.equal(previewTabs().length, 1);
  assert.strictEqual(previewTabs()[0], originalTab);
  for (let i = 0; i < 3; i++) {
    assert.equal((await v.commands.executeCommand('markdownPreviewViaJsTransforms.rerun')).status, 'success');
    assert.equal(previewTabs().length, 1);
    assert.strictEqual(previewTabs()[0], originalTab);
  }
  await v.window.showTextDocument(inputDocument, v.ViewColumn.One);
  await v.commands.executeCommand('markdownPreviewViaJsTransforms.reopenPreview');
  assert.strictEqual(previewTabs()[0], originalTab);
  await v.window.tabGroups.close(originalTab);
  await v.commands.executeCommand('markdownPreviewViaJsTransforms.reopenPreview');
  assert.equal(previewTabs().length, 1);
  await fs.writeFile(script, 'module.exports=()=>{while(true){}}');
  const pending = v.commands.executeCommand('markdownPreviewViaJsTransforms.rerun');
  await wait(250);
  await v.commands.executeCommand('markdownPreviewViaJsTransforms.cancel');
  assert.equal((await pending).status, 'cancelled');
  assert.equal(resultDocument.getText(), '# Saved edit\n\nChanged script');
  console.log(`MPJST_INTEGRATION_PASS vscode=${v.version} node=${process.versions.node}`);
};
